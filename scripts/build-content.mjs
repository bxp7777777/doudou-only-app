/* ---------------- 校验：只强制正文唯一与字数区间，标题允许复用 ---------------- */
function report(name, arr, min, max, expected) {
  const lens = arr.map((x) => len(x.body));
  const bad = arr.filter((x) => len(x.body) < min || len(x.body) > max);
  const titles = new Set(arr.map((x) => x.title));
  const bodies = new Set(arr.map((x) => x.body));
  console.log(`[${name}] 数量=${arr.length}/${expected} 唯一标题=${titles.size} 唯一正文=${bodies.size}`);
  console.log(`[${name}] 字数 min=${Math.min(...lens)} max=${Math.max(...lens)} 不达标=${bad.length}`);
  if (arr.length !== expected) throw new Error(`${name} 应 ${expected} 条，实际 ${arr.length}`);
  if (arr.length !== bodies.size) throw new Error(`${name} 正文存在重复`);
  if (bad.length) throw new Error(`${name} 有 ${bad.length} 条字数不在 ${min}-${max}：${bad[0].title}`);
}
