function makeTitleQueue(aList, bList, seed, skip = new Set()) {
  const all = [];
  for (const a of aList) {
    for (const b of bList) {
      const title = `${a}·${b}`;
      if (!skip.has(title)) all.push(title);
    }
  }
  const rr = makeRng(seed);
  for (let i = all.length - 1; i > 0; i--) {
    const j = Math.floor(rr() * (i + 1));
    [all[i], all[j]] = [all[j], all[i]];
  }
  return all;
}

let extBag = [];
function nextExt() {
  if (!extBag.length) {
    extBag = EXT.slice();
    for (let i = extBag.length - 1; i > 0; i--) {
      const j = Math.floor(r() * (i + 1));
      [extBag[i], extBag[j]] = [extBag[j], extBag[i]];
    }
  }
  return extBag.pop();
}

