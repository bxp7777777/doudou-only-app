function buildStory() {
  const open = pick(OPEN);
  const ap = pick(PIG_ACT);
  const ad = pick(DOG_ACT);
  const warm = pick(WARM);
  const sense = pick(SENSE);
  let parts = [open, ap, ad, warm, sense];
  let body = parts.join('');
  // 补到更丰满（目标 ≥150；远低于 300 上限，偏短篇才追加扩展句）
  const pool = EXT.slice();
  let guard = 0;
  while (len(body) < 150 && pool.length && guard++ < 6) {
    body += pool.splice(Math.floor(r() * pool.length), 1)[0];
  }
  body += pick(END);
  // 超 300 字：从末尾去掉扩展句/中段句精简
  while (len(body) > STORY_MAX && parts.length > 3) {
    parts.splice(3, 1);
    body = parts.join('') + pick(END);
  }
  const a = pick(TITLE_A), b = pick(TITLE_B);
  return { title: `${a}·${b}`, body };
}

