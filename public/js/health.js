/**
 * 温差综合健康提醒：只讲身体感受和健康动作，不做穿衣穿搭建议。
 * 按日期轮换挑两条，避免每天重复。
 */
const TIPS = [
  '昼夜温差大：多喝温水，护好肚子和脚，别对着风口吹。',
  '进出空调房先在门口缓一缓，出汗了马上擦干。',
  '屋里干燥的话，少量多次补水，护手霜随身带着。',
  '换季容易受凉：吃温的、少碰生冷，肠胃先稳住。',
  '室内外一冷一热，别直接灌冰饮，让身体慢慢缓过来。',
  '冷风直吹容易头疼：把风口调开，腰腹和脚踝别露着吹。',
  '暖气房待久了会干，放一杯水在桌上，提醒自己喝。',
  '坐久了腰先僵：每小时起身走两步，护好腰腹。'
];

function pick(dayIndex) {
  const i = Math.abs(dayIndex) % TIPS.length;
  const j = (i + 3) % TIPS.length;
  return [TIPS[i], TIPS[j]];
}

export { TIPS, pick };
